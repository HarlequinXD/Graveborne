    private static final int[][] GLYPHS = new int[128][];

    static {
        String[][] tables = {ROWS, ROWS2, ROWS3, ROWS4, ROWS5};
        int ci = 0;
        for (String[] t : tables) {
            int per = t.length / 7;
            for (int k = 0; k < per; k++) {
                int[] g = new int[7];
                for (int r = 0; r < 7; r++) {
                    String row = t[r * per + k];
                    int bits = 0;
                    // narrow glyphs are centred in the 5-wide cell
                    String pad = row.length() == 3 ? "0" + row + "0" : row;
                    for (int b = 0; b < 5; b++) if (pad.charAt(b) == '1') bits |= (16 >> b);
                    g[r] = bits;
                }
                GLYPHS[CHARS.charAt(ci++)] = g;
            }
        }
    }

    static int[] glyph(char c) {
        return c < 128 ? GLYPHS[c] : null;
    }
